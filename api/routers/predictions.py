import csv
from functools import lru_cache
from pathlib import Path

from fastapi import APIRouter, Query, HTTPException

router = APIRouter(tags=["predictions"])


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CSV_PATH = ROOT / "evaluation" / "results_resnet.csv"
FALLBACK_CSV_PATH = ROOT / "evaluation" / "results.csv"

VALID_LABELS = {"no-damage", "minor-damage", "major-damage", "destroyed"}


@lru_cache(maxsize=4)
def load_tile_predictions(csv_path: str) -> dict[str, str]:
    """
    Load predictions mapping from image filename (e.g., *_post_disaster.png) -> label.
    Cached because the frontend may request repeatedly.
    """
    path = Path(csv_path)
    if not path.exists():
        raise FileNotFoundError(str(path))

    out: dict[str, str] = {}
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            img = (row.get("image_name") or "").strip()
            pred = (row.get("vlm_prediction") or "").strip().lower()
            if not img or pred not in VALID_LABELS:
                continue
            out[img] = pred
    return out


def resolve_predictions_source() -> dict[str, str]:
    """
    Prefer `evaluation/results_resnet.csv` (generated by ResNet batch),
    but fall back to `evaluation/results.csv` so the endpoint still works.
    """
    try:
        return load_tile_predictions(str(DEFAULT_CSV_PATH))
    except FileNotFoundError:
        return load_tile_predictions(str(FALLBACK_CSV_PATH))


@router.get("/predictions/tiles")
def get_tile_predictions(
    prefix: str = Query(default="socal-fire_", description="Filename prefix to include."),
    phase: str = Query(default="both", description="Which tile phases to return: pre|post|both."),
) -> dict:
    if phase not in {"pre", "post", "both"}:
        raise HTTPException(status_code=400, detail="phase must be one of: pre, post, both")

    predictions_by_post = resolve_predictions_source()

    filtered: dict[str, str] = {}
    for filename, label in predictions_by_post.items():
        if not filename.startswith(prefix):
            continue
        if phase in {"post", "both"} and filename.endswith("_post_disaster.png"):
            filtered[filename] = label

        if phase in {"pre", "both"} and filename.endswith("_post_disaster.png"):
            pre_name = filename.replace("_post_disaster.png", "_pre_disaster.png")
            filtered[pre_name] = label

    return {
        "prefix": prefix,
        "phase": phase,
        "predictions": filtered,
    }

